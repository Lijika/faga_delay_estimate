#!/usr/bin/env python3
"""Generate src/embedded_arch.{h,cpp} from the official SRB architecture files.

The evaluation container ships no architecture files (the image only creates
/app/{program,input,output,ans,...}), so a submitted binary must carry the SRB
architecture itself.  This generator turns the five official JSON files into one
translation unit with raw string literals and a name -> text lookup.

The files are read from doc/eda比赛文件/arch and hashed; the hashes are written
into the generated header so a rebuild can prove which architecture was embedded.

usage: python3 scripts/gen_embedded_arch.py [--arch DIR] [--out DIR] [--check]
       --check  only verify that the existing generated file matches the inputs
"""
import argparse
import hashlib
import pathlib
import sys

FILES = ("SRB_Port.json", "SRB_Arc.json", "SRB_Net.json", "SRB_Inst.json", "SRB_Gap.json")
DELIM = "SRBARCHJSON"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arch", default="doc/eda比赛文件/arch")
    ap.add_argument("--out", default="src")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    arch = pathlib.Path(args.arch)
    out = pathlib.Path(args.out)
    texts, hashes = {}, {}
    for name in FILES:
        p = arch / name
        if not p.is_file():
            raise SystemExit(f"missing architecture file: {p}")
        data = p.read_bytes()
        if DELIM.encode() in data:
            raise SystemExit(f"{p}: raw string delimiter {DELIM} occurs in the file")
        texts[name] = data.decode("utf-8")
        hashes[name] = sha256(p)

    header = ['// Generated by scripts/gen_embedded_arch.py -- do not edit.',
              '// Official SRB architecture embedded for the self-contained submission build.',
              '#pragma once',
              '',
              'namespace delayest {',
              'namespace embedded_arch {',
              '',
              '// Returns the embedded text of one of the five architecture files, or nullptr.',
              'const char* text(const char* name);',
              '',
              'constexpr const char* kSourceHashes[] = {']
    for name in FILES:
        header.append(f'    "{name} {hashes[name]}",')
    header += ['};', '', '}  // namespace embedded_arch', '}  // namespace delayest', '']

    body = ['// Generated by scripts/gen_embedded_arch.py -- do not edit.',
            '#include "embedded_arch.h"',
            '',
            '#include <cstring>',
            '',
            'namespace delayest {',
            'namespace embedded_arch {',
            'namespace {',
            '']
    for i, name in enumerate(FILES):
        body.append(f'// {name} ({hashes[name]})')
        body.append(f'const char kFile{i}[] = R"{DELIM}(')
        body.append(texts[name])
        body.append(f'){DELIM}";')
        body.append('')
    body += ['}  // namespace', '',
             'const char* text(const char* name) {',
             '  if (name == nullptr) return nullptr;']
    for i, name in enumerate(FILES):
        body.append(f'  if (std::strcmp(name, "{name}") == 0) return kFile{i};')
    body += ['  return nullptr;', '}', '',
             '}  // namespace embedded_arch', '}  // namespace delayest', '']

    header_text = "\n".join(header)
    body_text = "\n".join(body)
    hpath, cpath = out / "embedded_arch.h", out / "embedded_arch.cpp"

    if args.check:
        ok = True
        for path, want in ((hpath, header_text), (cpath, body_text)):
            have = path.read_text() if path.is_file() else ""
            if have != want:
                print(f"stale: {path}", file=sys.stderr)
                ok = False
        if not ok:
            return 1
        print("embedded_arch.{h,cpp} match " + ", ".join(FILES))
        return 0

    out.mkdir(parents=True, exist_ok=True)
    hpath.write_text(header_text)
    cpath.write_text(body_text)
    total = sum(len(t) for t in texts.values())
    print(f"wrote {hpath} and {cpath}: {len(FILES)} files, {total} bytes of JSON")
    for name in FILES:
        print(f"  {name} {hashes[name]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
